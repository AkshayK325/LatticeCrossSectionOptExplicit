"""H series (EPU 45) vs F series (linear E = 40): beam model (ours) vs Abaqus solid, on observable quantities.

    PYTHONPATH=src python abaqus/h_series_analysis.py      (after compare.py has written abaqus/ours/<name>.csv)

Per case:
- max stroke and its time;
- energy absorbed vs stroke on the loading branch (KE0 - KE of the impactor, the F-series metric: notes/15,
  BENCHMARK_PLAN "Results 2026-10-08") at 25 / 50 / 75 / 95 % of the Abaqus max stroke;
- peak bottom reaction;
- rebound: impactor KE at the end / KE0 (= 1 - energy lost; both codes, independent of how each books viscous
  dissipation: Abaqus/Explicit here reports ALLCD = 0 and keeps it in ALLSE).
Writes abaqus/results/H_series_summary.md and prints it.
"""
import csv
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT))
import cases                                                     # noqa: E402
import compare                                                   # noqa: E402

PAIRS = [('H1a', 'F1a'), ('H1c', 'F1c'), ('H1d', 'F1d'), ('H1e', 'F1e'), ('H1f', 'F1f'), ('H1i', 'F1i'), ('H1j', 'F1j')]
FRACS = (0.25, 0.5, 0.75, 0.95)


def ours_csv(name):
    p = ROOT / 'ours' / f'{name}.csv'
    if not p.exists():
        return None
    rows = list(csv.DictReader(open(p)))
    return {k: np.array([float(r[k]) for r in rows]) for k in rows[0]}


def loading_curve(t, u, ke):
    """Stroke (positive) and absorbed energy KE0 - KE on the loading branch (until max stroke)."""
    s = -u
    k = int(np.argmax(s))
    return s[:k + 1], ke[0] - ke[:k + 1], t[k], s[k]


def absorbed_at(s, e, s_q):
    sm = np.maximum.accumulate(s)                                 # monotone for interpolation
    _, idx = np.unique(sm, return_index=True)
    return np.interp(s_q, sm[idx], e[idx], right=np.nan)


def metrics(case):
    c = cases.CASES[case]
    name = c['spec']['name']
    ab = compare.read_abaqus(name)
    ours = ours_csv(name)
    if ab is None or ours is None:
        return None
    L = compare.labels(case)
    ua = compare.pick(ab, 'U3', ('node', L['ref']))
    ka = compare.pick(ab, 'ALLKE')
    if abs(ours['ALLKE'][0] / ka[1][0] - 1) > 0.01:              # compare.py saves the nominal run: energy-match it
        jm = c.get('joint', c['spec'].get('joint'))
        ours = cases.a4_ours(dict(c['spec'], energy_J=ka[1][0] * 1e-3, joint=jm))
    ra = compare.pick(ab, 'RF3', ('sum', L['bot']))
    ta, ua_ = ua
    kea = np.interp(ta, ka[0], ka[1])
    sa, ea, tma, sma = loading_curve(ta, ua_, kea)
    so, eo, tmo, smo = loading_curve(ours['time'], ours['U3ref'], ours['ALLKE'])
    q = np.array(FRACS) * sma
    Ea, Eo = absorbed_at(sa, ea, q), absorbed_at(so, eo, q)
    out = dict(name=name, stroke=(smo, sma), tmax=(tmo, tma), dE=(Eo / Ea - 1),
               peak=(np.abs(ours['RF3bot']).max(), np.abs(ra[1]).max()),
               reb=(ours['ALLKE'][-1] / ours['ALLKE'][0], ka[1][-1] / ka[1][0]),
               T=(ours['time'][-1], ka[0][-1]), ke0=(ours['ALLKE'][0], ka[1][0]))
    return out


def main():
    lines = ['# H series (EPU 45 visco-hyperelastic) vs F series (linear E = 40): beam model vs Abaqus solid', '',
             'Generated by `abaqus/h_series_analysis.py`. Ours = beam model with JOINT_FHS (energy-matched to the solid by '
             '`compare.py` when the solid KE(0) differs by > 1 %). Energy absorbed = impactor KE0 - KE on the loading '
             'branch, at the given fraction of the Abaqus max stroke (the F-series metric).', '',
             '| case | max stroke ours / Abaqus (err) | time of max ours / Abaqus | energy absorbed err at 25 / 50 / 75 / 95 % | '
             'peak bottom reaction ours / Abaqus | rebound KE / KE0 ours / Abaqus |',
             '|---|---|---|---|---|---|']
    res = {}
    for h, f in PAIRS:
        for case in (h, f):
            m = metrics(case)
            res[case] = m
            if m is None:
                lines.append(f'| {case} | (no ours or no Abaqus CSV) | | | | |')
                continue
            so, sa = m['stroke']
            lines.append(f"| {case} | {so:.3f} / {sa:.3f} mm ({100 * (so / sa - 1):+.1f} %) | {1e3 * m['tmax'][0]:.2f} / "
                         f"{1e3 * m['tmax'][1]:.2f} ms | " + ' / '.join('—' if np.isnan(x) else f'{100 * x:+.1f}' for x in m['dE'])
                         + f" % | {m['peak'][0]:.1f} / {m['peak'][1]:.1f} N | {m['reb'][0]:.3f} / {m['reb'][1]:.3f} |")
    lines += ['']
    (ROOT / 'results' / 'H_series_summary.md').write_text('\n'.join(lines) + '\n')
    print('\n'.join(lines))
    return res


if __name__ == '__main__':
    main()
