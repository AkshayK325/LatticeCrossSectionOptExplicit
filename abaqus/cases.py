# EPU 45, linear-elastic level-A material: instantaneous modulus E0 (what governs a ms-scale impact)
E0, NU, RHO = 342.9, 0.49, 1.06e-9
G0 = E0 / (2 * (1 + NU))
KAPPA = 6 * (1 + NU) / (7 + 6 * NU)          # Cowper shear coefficient of a solid circle (= ours)


def _fmt_rows(rows, per_line=8):
    """Abaqus data lines: at most 16 entries per line; keep it short for readability."""
    out = []
    for r in rows:
        out.append(', '.join(f'{v:.10g}' if isinstance(v, float) else str(v) for v in r))
    return '\n'.join(out)


