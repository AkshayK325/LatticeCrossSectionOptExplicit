            P, T = solid.gmsh_from_stl(stl, c['h'], curvature=0, plate_refine=pr, **c.get('fmesh', F_MESH))
            P, T, info['slivers_removed'] = solid.remove_boundary_slivers(P, T, 0.25 * c['h'])
            info['stl'] = str(stl.relative_to(ROOT.parent))
