    fr, law, m, j, A, I = _ours_beam(X, conn, np.full(n_el, c['r']))
    top, mid = n_el, n_el // 2
    m = m.clone()
    m[top] += c['M']
    fix_u = torch.zeros(fr.N, 3, dtype=torch.bool)
    fix_r = torch.zeros(fr.N, 3, dtype=torch.bool)
