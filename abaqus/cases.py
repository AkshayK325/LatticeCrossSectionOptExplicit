"""Abaqus/Explicit benchmark cases: one definition per case, used both to write the Abaqus .inp and to run our
solver with exactly the same model (geometry, material, loads, outputs). Units mm, N, s, t, MPa.

    PYTHONPATH=src python abaqus/cases.py A1            # write abaqus/inp/A1_cantilever.inp
    PYTHONPATH=src python abaqus/compare.py A1          # run ours, overlay Abaqus if abaqus/csv/A1_*.csv exists

Level A (code verification): Abaqus B31 beams with the same idealisation as ours (linear elastic, no Prony).
See abaqus/BENCHMARK_PLAN.md.
"""
import math
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parent

# EPU 45, linear-elastic level-A material: instantaneous modulus E0 (what governs a ms-scale impact)
E0, NU, RHO = 342.9, 0.49, 1.06e-9
G0 = E0 / (2 * (1 + NU))
KAPPA = 6 * (1 + NU) / (7 + 6 * NU)          # Cowper shear coefficient of a solid circle (= ours)


def _fmt_rows(rows, per_line=8):
    """Abaqus data lines: at most 16 entries per line; keep it short for readability."""
    out = []
    for r in rows:
        out.append(', '.join(f'{v:.10g}' if isinstance(v, float) else str(v) for v in r))
    return '\n'.join(out)


# ------------------------------------------------------------------------------------------------ A1
A1 = dict(name='A1_cantilever', L=20.0, n_el=20, r=0.8, P=0.4, T=10e-3, out_dt=1e-5,
          title='A1: clamped cantilever, suddenly applied constant tip load P (fixed direction, +z), '
                'large rotation; linear elastic E0, Timoshenko (Cowper kappa), no damping')


def a1_mesh(c=A1):
    n = c['n_el']
    X = np.stack([np.linspace(0, c['L'], n + 1), np.zeros(n + 1), np.zeros(n + 1)], 1)
    conn = np.stack([np.arange(n), np.arange(1, n + 1)], 1)
    return X, conn


def a1_inp(c=A1):
    X, conn = a1_mesh(c)
    r = c['r']
    A = math.pi * r**2
    ks = KAPPA * G0 * A                                     # transverse shear stiffness kappa G A
    nodes = _fmt_rows([(i + 1, *map(float, x)) for i, x in enumerate(X)])
    elems = _fmt_rows([(e + 1, int(a) + 1, int(b) + 1) for e, (a, b) in enumerate(conn)])
    tip = len(X)
    return f"""*HEADING
{c['title']}
** Generated by abaqus/cases.py (LatticeCrossSectionOptExplicit). Units: mm, N, s, tonne, MPa.
** Our model: src/explicitFE.py corotational Timoshenko beam, elastic_law, lumped mass, velocity Verlet.
*NODE
{nodes}
*ELEMENT, TYPE=B31, ELSET=BEAM
{elems}
*NSET, NSET=ROOT
1
*NSET, NSET=TIP
{tip}
*BEAM SECTION, ELSET=BEAM, MATERIAL=EPU45_LIN, SECTION=CIRC
{r:.10g}
0., 1., 0.
** kappa G A with kappa = 6(1+nu)/(7+6nu) = {KAPPA:.6f} (the same shear coefficient as ours)
*TRANSVERSE SHEAR STIFFNESS
{ks:.10g}, {ks:.10g}
*MATERIAL, NAME=EPU45_LIN
*DENSITY
{RHO:.10g},
*ELASTIC
{E0:.10g}, {NU:.10g}
** constant amplitude 1 from t = 0: the load is applied suddenly
*AMPLITUDE, NAME=CONST
0., 1., 1., 1.
*BOUNDARY
ROOT, ENCASTRE
*STEP, NAME=LOAD, NLGEOM=YES
*DYNAMIC, EXPLICIT
, {c['T']:.10g}
** no bulk viscosity: ours has no numerical damping (energy-conserving comparison)
*BULK VISCOSITY
0., 0.
*CLOAD, AMPLITUDE=CONST
TIP, 3, {c['P']:.10g}
*OUTPUT, FIELD, NUMBER INTERVAL=50
*NODE OUTPUT
U, UR, V
*OUTPUT, HISTORY, TIME INTERVAL={c['out_dt']:.10g}
*NODE OUTPUT, NSET=TIP
U1, U2, U3, UR1, UR2, UR3, V3
*NODE OUTPUT, NSET=ROOT
RF3, RM2
*ENERGY OUTPUT
ALLKE, ALLIE, ALLSE, ALLWK, ETOTAL, ALLAE, ALLVD
*END STEP
"""


def a1_ours(c=A1):
    """Our solver on the same model. Returns dict of time histories (tip U1, U3, UR2 (rotation angle about y),
    root RF3, energies)."""
    import torch
    from explicitFE import Frame, lumped_mass, stable_dt, log_so3
    from explicitSolve import simulate, strain_energy
    from latticeSetup import circle_sections
    torch.set_default_dtype(torch.float64)
    X, conn = a1_mesh(c)
    fr = Frame(X, conn)
    r = torch.full((c['n_el'],), c['r'])
    A, I = circle_sections(r, nu=NU)
    law = lambda d: fr.elastic_law(d, A, I, E0, G0)
    m, j = lumped_mass(fr, A, I, RHO)
    dt, _ = stable_dt(fr, law, m, j, courant=0.8)
    n = int(math.ceil(c['T'] / dt))
    dt = c['T'] / n
    fix = torch.zeros(fr.N, 3, dtype=torch.bool)
    fix[0] = True
    tip = fr.N - 1
    F = torch.zeros(fr.N, 3)
    F[tip, 2] = c['P']
    Z = torch.zeros(fr.N, 3)
    rec = max(1, int(round(c['out_dt'] / dt)))

    def cb(k, t, state, fint):
        u, v, R, w = state
        fu, fth, d, f_loc = fint[:4]
        ke = 0.5 * (m * (v**2).sum(1)).sum() + 0.5 * (j * (w**2).sum(1)).sum()
        se = strain_energy(d, f_loc)
        th = log_so3(R[tip:tip + 1])[0]
        return {'U1': u[tip, 0].item(), 'U2': u[tip, 1].item(), 'U3': u[tip, 2].item(), 'UR2': th[1].item(),
                'V3': v[tip, 2].item(), 'RF3': fu[0, 2].item(), 'ALLKE': ke.item(), 'ALLSE': se.item(),
                'ALLWK': c['P'] * u[tip, 2].item()}
    with torch.no_grad():
        h = simulate(fr, law, m, j, dt, n, fix_u=fix, fix_r=fix, f_ext=lambda t: (F, Z), record_every=rec,
                     callback=cb)
    out = {'time': np.asarray(h['t'])}
    for k in ('U1', 'U2', 'U3', 'UR2', 'V3', 'RF3', 'ALLKE', 'ALLSE', 'ALLWK'):
        out[k] = np.asarray(h[k])
    out['dt'], out['n_steps'] = dt, n
    return out


CASES = {'A1': dict(spec=A1, inp=a1_inp, ours=a1_ours)}


def write_inp(case):
    c = CASES[case]
    p = ROOT / 'inp' / f"{c['spec']['name']}.inp"
    p.parent.mkdir(exist_ok=True)
    p.write_text(c['inp']())
    return p


if __name__ == '__main__':
    for case in (sys.argv[1:] or list(CASES)):
        print('wrote', write_inp(case))
