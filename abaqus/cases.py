def a3_ours(c=A3):
    import torch
    from explicitFE import stable_dt
    from explicitSolve import simulate, strain_energy
    from contact import LineContact, potential_force
    X, conn = a3_mesh(c)
    n = c['n_el']
    r_e = np.concatenate((np.full(n, c['rA']), np.full(n, c['rB'])))
    fr, law, m, j, A, I = _ours_beam(X, conn, r_e)
    beam = torch.cat((torch.zeros(n, dtype=torch.long), torch.ones(n, dtype=torch.long)))
    sc = LineContact(fr, torch.as_tensor(r_e), beam, E0, NU)
    fix = torch.zeros(fr.N, 3, dtype=torch.bool)
    fix[[0, n]] = True
    v0 = torch.zeros(fr.N, 3)
    v0[n + 1:, 2] = -c['vB']
    _, wb = stable_dt(fr, law, m, j)
    # contact frequency bound: one quadrature point of line stiffness on the lightest node
    dt = 0.7 * 2 / math.sqrt(wb**2 + 2 * sc.k_line * 1.0 / m.min().item())
    nst = int(math.ceil(c['T'] / dt))
    dt = c['T'] / nst
    rec = max(1, int(round(c['out_dt'] / dt)))
    a_mid, b_mid = n // 2, n + 1 + n // 2
    bn = torch.arange(n + 1, 2 * n + 2)
    contact = lambda u, v: potential_force(sc.energy, fr.X + u)[0]

    def cb(k, t, state, fint):
        u, v, R, w = state
        fu, fth, d, f_loc = fint[:4]
        ke = 0.5 * (m * (v**2).sum(1)).sum() + 0.5 * (j * (w**2).sum(1)).sum()
        phi = sc.energy(fr.X + u)[0]
        return {'U3Bmid': u[b_mid, 2].item(), 'V3Bmid': v[b_mid, 2].item(), 'U3Amid': u[a_mid, 2].item(),
                'V3Amid': v[a_mid, 2].item(), 'PB3': (m[bn] * v[bn, 2]).sum().item(), 'ALLKE': ke.item(),
                'ALLSE': strain_energy(d, f_loc).item(), 'PHIC': phi.item()}
    with torch.no_grad():
        h = simulate(fr, law, m, j, dt, nst, v0=v0, fix_u=fix, fix_r=fix, contact=contact, record_every=rec,
                     callback=cb)
    out = _pack(h, ('U3Bmid', 'V3Bmid', 'U3Amid', 'V3Amid', 'PB3', 'ALLKE', 'ALLSE', 'PHIC'), dt, nst)
    out['massB'] = m[bn].numpy()                         # lumped nodal masses of B (same lumping as Abaqus B31)
    return out


