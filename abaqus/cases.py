def a1_ours(c=A1):
    """Our solver on the same model. Returns dict of time histories (tip U1, U3, UR2 (rotation angle about y),
    root RF3, energies)."""
    import torch
    from explicitFE import Frame, lumped_mass, stable_dt, log_so3
    from explicitSolve import simulate, strain_energy
    from latticeSetup import circle_sections
    torch.set_default_dtype(torch.float64)
    X, conn = a1_mesh(c)
    fr = Frame(X, conn)
    r = torch.full((c['n_el'],), c['r'])
    A, I = circle_sections(r, nu=NU)
    law = lambda d: fr.elastic_law(d, A, I, E0, G0)
    m, j = lumped_mass(fr, A, I, RHO)
    dt, _ = stable_dt(fr, law, m, j, courant=0.8)
    n = int(math.ceil(c['T'] / dt))
    dt = c['T'] / n
    fix = torch.zeros(fr.N, 3, dtype=torch.bool)
    fix[0] = True
    tip = fr.N - 1
    F = torch.zeros(fr.N, 3)
    F[tip, 2] = c['P']
    Z = torch.zeros(fr.N, 3)
    rec = max(1, int(round(c['out_dt'] / dt)))

    def cb(k, t, state, fint):
        u, v, R, w = state
        fu, fth, d, f_loc = fint[:4]
        ke = 0.5 * (m * (v**2).sum(1)).sum() + 0.5 * (j * (w**2).sum(1)).sum()
        se = strain_energy(d, f_loc)
        th = log_so3(R[tip:tip + 1])[0]
        return {'U1': u[tip, 0].item(), 'U2': u[tip, 1].item(), 'U3': u[tip, 2].item(), 'UR2': th[1].item(),
                'V3': v[tip, 2].item(), 'RF3': fu[0, 2].item(), 'ALLKE': ke.item(), 'ALLSE': se.item(),
                'ALLWK': c['P'] * u[tip, 2].item()}
    with torch.no_grad():
        h = simulate(fr, law, m, j, dt, n, fix_u=fix, fix_r=fix, f_ext=lambda t: (F, Z), record_every=rec,
                     callback=cb)
    out = {'time': np.asarray(h['t'])}
    for k in ('U1', 'U2', 'U3', 'UR2', 'V3', 'RF3', 'ALLKE', 'ALLSE', 'ALLWK'):
        out[k] = np.asarray(h[k])
    out['dt'], out['n_steps'] = dt, n
    return out


# ------------------------------------------------------------------------------------------------ shared
SCF_OFF = 1e-8      # Abaqus B31 slenderness compensation factor (default 0.25 scales kappa G A down by
                    # 1/(1 + 0.25 l^2 A / 12 I): -8% on 0.8 mm elements of r 0.8). Ours has no such factor.


def _section(elset, r, n1, scf=None, E=E0):
    """*BEAM SECTION + *TRANSVERSE SHEAR STIFFNESS (kappa G A; third entry = slenderness compensation factor,
    given only when scf is not None: SCF_OFF effectively switches Abaqus's short-element shear reduction off)."""
    A = math.pi * r**2
    ks = KAPPA * E / (2 * (1 + NU)) * A
    extra = '' if scf is None else f', {scf:.10g}'
    return f"""*BEAM SECTION, ELSET={elset}, MATERIAL=EPU45_LIN, SECTION=CIRC
{r:.10g}
{n1[0]:.10g}, {n1[1]:.10g}, {n1[2]:.10g}
*TRANSVERSE SHEAR STIFFNESS
{ks:.10g}, {ks:.10g}{extra}"""


def material_block(E=E0, material=None):
    if material == 'epu45':
        return epu45_block()
    return f"""*MATERIAL, NAME=EPU45_LIN
*DENSITY
{RHO:.10g},
*ELASTIC
{E:.10g}, {NU:.10g}"""


def epu45_block():
    """EPU 45 visco-hyperelastic (config/materials.yaml, the beam's ViscoHyperLaw data): Yeoh long-term + 1-term
    Prony on shear (k1 = 0). D1 = 2 / K with K from the INSTANTANEOUS E0 and nu 0.49, so the solid's impact-rate
    response (E0, nu) and dilatational wave speed equal the beam model's and the linear E0 runs'."""
    from material import epu45
    m = epu45()
    K = m['E0'] / (3 * (1 - 2 * m['nu']))
    C10, C20, C30 = m['yeoh']
    prony = '\n'.join(f"{g:.10g}, 0., {t:.10g}" for g, t in zip(m['prony_g'], m['prony_tau']))
    return f"""*MATERIAL, NAME=EPU45
** Yeoh long-term C10, C20, C30 [MPa]; D1 = 2/K, K = E0/(3(1-2nu)) = {K:.6g} MPa (E0 {m['E0']:.6g}, nu {m['nu']:g})
*DENSITY
{m['rho']:.10g},
*HYPERELASTIC, YEOH, MODULI=LONG TERM
{C10:.10g}, {C20:.10g}, {C30:.10g}, {2 / K:.10g}, 0., 0.
*VISCOELASTIC, TIME=PRONY
{prony}"""


MATERIAL_BLOCK = material_block()


def _ours_beam(X, conn, r_e):
    """Frame, linear-elastic Timoshenko law (Cowper kappa), lumped mass: the level-A model."""
    import torch
    from explicitFE import Frame, lumped_mass
    from latticeSetup import circle_sections
    torch.set_default_dtype(torch.float64)
    fr = Frame(X, conn)
    r = torch.as_tensor(r_e, dtype=torch.float64)
    A, I = circle_sections(r, nu=NU)
    law = lambda d: fr.elastic_law(d, A, I, E0, G0)
    m, j = lumped_mass(fr, A, I, RHO)
    return fr, law, m, j, A, I


def _pack(h, keys, dt, n):
    out = {'time': np.asarray(h['t'])}
    for k in keys:
        out[k] = np.asarray(h[k])
    out['dt'], out['n_steps'] = dt, n
    return out


