def _ogrid(R, n, m, bias=1.0):
    """2D O-grid of a disc of radius R: centre square (half side R/2, n x n quads) + 4 blocks (n x m) to the
    circle; bias > 1 makes the radial layers thinner toward the surface (f = 1 - (1 - u)^bias).
    Returns (P (k,2), Q (q,4) counter-clockwise quads, index of the centre node)."""
    a = 0.5 * R
    pts, idx = [], {}

    def node(p):
        key = (round(p[0], 9), round(p[1], 9))
        if key not in idx:
            idx[key] = len(pts)
            pts.append(p)
        return idx[key]
    quads = []
    g = np.linspace(-a, a, n + 1)
    sq = [[node((g[i], g[j])) for j in range(n + 1)] for i in range(n + 1)]
    for i in range(n):
        for j in range(n):
            quads.append((sq[i][j], sq[i + 1][j], sq[i + 1][j + 1], sq[i][j + 1]))
    for k in range(4):                                     # sides: +x, +y, -x, -y (rotate the +x block)
        c, s_ = math.cos(k * math.pi / 2), math.sin(k * math.pi / 2)
        rot = lambda p: (c * p[0] - s_ * p[1], s_ * p[0] + c * p[1])
        grid = []
        for i in range(n + 1):
            t = -1 + 2 * i / n
            ps = (a, a * t)
            th = t * math.pi / 4
            pa = (R * math.cos(th), R * math.sin(th))
            grid.append([node(rot(((1 - f) * ps[0] + f * pa[0], (1 - f) * ps[1] + f * pa[1])))
                         for f in 1 - (1 - np.linspace(0, 1, m + 1)) ** bias])
        for i in range(n):
            for j in range(m):
                q = (grid[i][j], grid[i][j + 1], grid[i + 1][j + 1], grid[i + 1][j])
                quads.append(q)
    P = np.array(pts)
    Q = np.array(quads)
    # make every quad counter-clockwise
    for r_, q in enumerate(Q):
        x, y = P[q, 0], P[q, 1]
        if 0.5 * np.sum(x * np.roll(y, -1) - np.roll(x, -1) * y) < 0:
            Q[r_] = q[::-1]
    return P, Q, idx[(0.0, 0.0)]


def _graded(L, ds_min, ds_max, growth):
    """Axial coordinates on [-L/2, L/2], symmetric, ds_min at 0 growing geometrically to ds_max."""
    half, x, d = [0.0], 0.0, ds_min
    while x + d < L / 2 - 1e-12:
        x += d
        half.append(x)
        d = min(d * growth, ds_max)
    half = np.array(half)
    if L / 2 - half[-1] < 0.5 * d:                      # merge a sliver into the last interval
        half = half[:-1]
    half = np.append(half, L / 2)
    return np.concatenate((-half[:0:-1], half))


def _cylinder(R, L, axis, z0, n, m, ds, node0, elem0, bias=1.0, s=None):
    """Hex mesh of a cylinder along 'x' or 'y' centred at the origin (axis height z0). Returns nodes (k,3),
    C3D8R connectivity (1-based labels), axis-mid node label, end-face node labels, nodal lumped masses."""
    P, Q, c0 = _ogrid(R, n, m, bias)
    if s is None:
        s = np.linspace(-L / 2, L / 2, int(round(L / ds)) + 1)
    ns = len(s) - 1
    k = len(P)
    X = []
    for sv in s:
        for p in P:
            X.append((sv, p[0], z0 + p[1]) if axis == 'x' else (p[0], sv, z0 + p[1]))
    X = np.array(X)
    E = []
    for i in range(ns):
        for q in Q:
            E.append([i * k + v for v in q] + [(i + 1) * k + v for v in q])
    E = np.array(E)
    # orientation: positive Jacobian (1->2, 1->4, 1->5 right-handed), else mirror the quad order
    for r_, e in enumerate(E):
        J = np.linalg.det(np.stack((X[e[1]] - X[e[0]], X[e[3]] - X[e[0]], X[e[4]] - X[e[0]])))
        if J < 0:
            E[r_] = e[[0, 3, 2, 1, 4, 7, 6, 5]]
    # lumped mass: element volume / 8 per node (one-point C3D8R, parallelepiped estimate is enough here)
    m_n = np.zeros(len(X))
    for e in E:
        x = X[e]
        V = abs(np.linalg.det(np.stack((x[1] - x[0], x[3] - x[0], x[4] - x[0])))) * 0.5 + \
            abs(np.linalg.det(np.stack((x[5] - x[6], x[7] - x[6], x[2] - x[6])))) * 0.5
        m_n[e] += RHO * V / 8
    mid = node0 + (ns // 2) * k + c0 + 1
    axis_nodes = [node0 + i * k + c0 + 1 for i in range(ns + 1)]
    ends = list(range(node0 + 1, node0 + k + 1)) + list(range(node0 + ns * k + 1, node0 + (ns + 1) * k + 1))
    return X, E + node0 + 1, mid, ends, m_n, axis_nodes


